"""Neuronpedia descriptions for the probes' top SAE features.

    uv run python scripts/analysis/neuronpedia.py

Reads the top_features_sae16k_last@L{layer}.json files of the main probe run and writes
results/analysis/neuronpedia_features.csv: auto-generated description, top output tokens
and the text around the strongest activations. Neuronpedia's source
"{layer}-gemmascope-2-res-16k" is google/gemma-scope-2-4b-it resid_post layer_{layer}
_width_16k_l0_medium, the SAE the probes use. Descriptions are generated by an LLM over
chat data (lmsys + oasst1), so they are hypotheses to check against our questions.
"""

from __future__ import annotations

import glob
import json
import time
import urllib.request

import pandas as pd

from saerag.config import REPO_ROOT

RUN = "results/sagemaker/probes/gemma3-4b-it/miss_as_retrieve/*__l2"
LAYERS = [17, 22, 29]
API = "https://www.neuronpedia.org/api/feature/gemma-3-4b-it/{layer}-gemmascope-2-res-16k/{index}"


def fetch(layer: int, index: int) -> dict:
    req = urllib.request.Request(API.format(layer=layer, index=index), headers={"User-Agent": "saerag"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def context(act: dict, before: int = 12) -> str:
    i = act["maxValueTokenIndex"]
    return "".join(act["tokens"][max(0, i - before): i + 1]).replace("\n", " ").strip()


def main() -> None:
    run = sorted(glob.glob(str(REPO_ROOT / RUN)))[0]
    rows = []
    for L in LAYERS:
        top = json.load(open(f"{run}/top_features_sae16k_last@L{L}.json"))
        for cls, feats in top.items():
            for rank, f in enumerate(feats, 1):
                d = fetch(L, f)
                time.sleep(0.2)
                assert d["source"]["hfFolderId"] == f"resid_post/layer_{L}_width_16k_l0_medium"
                rows.append({"layer": L, "class": cls, "rank": rank, "feature": f,
                             "description": "; ".join(e["description"] for e in d.get("explanations", [])),
                             "top_output_tokens": " ".join(t.strip() for t in d.get("pos_str", [])[:8]),
                             "density": d.get("frac_nonzero"),
                             "example_contexts": " || ".join(context(a) for a in d.get("activations", [])[:3]),
                             "url": f"https://www.neuronpedia.org/gemma-3-4b-it/{L}-gemmascope-2-res-16k/{f}"})
            print(f"L{L} {cls}: done", flush=True)
    out = REPO_ROOT / "results" / "analysis" / "neuronpedia_features.csv"
    pd.DataFrame(rows).to_csv(out, index=False)
    print(f"wrote {out} ({len(rows)} features)")


if __name__ == "__main__":
    main()
